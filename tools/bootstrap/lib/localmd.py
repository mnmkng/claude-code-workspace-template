"""Structure of the root CLAUDE.local.md (gitignored team-context + personal file).

CLAUDE.local.md is @imported by the committed root CLAUDE.md (its last line is
`@CLAUDE.local.md`). The bootstrap uses it for two cleanly separated purposes,
each in its own delimited region:

  1. A team-context block (managed by compose / cloud apply) whose @imports load
     the team's CLAUDE.md chain. This is WORKSPACE context, not personal notes.
  2. Personal context below it (synced from WORKSPACE_PERSONAL_GIST by personal.py,
     or hand-authored by an engineer).

Putting the team imports here - in a gitignored file - means composition never
dirties a tracked file. They used to live in a marker block appended to the
tracked CLAUDE.md, which dirtied the worktree every session and tripped the
platform's Stop hook (see #72). The two regions are delimited so each writer
owns exactly one and neither clobbers the other, regardless of call order.
"""

import re


TEAM_START = "<!-- WORKSPACE-BOOTSTRAP:TEAM-CONTEXT:BEGIN -->"
TEAM_END = "<!-- WORKSPACE-BOOTSTRAP:TEAM-CONTEXT:END -->"

# Loaded into the model's context (it lives in an @imported file), so it speaks
# to a future Claude: these imports are workspace framing, not the human's notes.
_TEAM_DOC = (
    "<!-- Auto-generated by tools/bootstrap - do NOT hand-edit. These @imports\n"
    "     load your team's CLAUDE.md chain (workspace context). This is NOT the\n"
    "     user's personal context; anything below the END marker is. Regenerated\n"
    "     every session. -->"
)

_TEAM_BLOCK_RE = re.compile(
    re.escape(TEAM_START) + r".*?" + re.escape(TEAM_END) + r"[^\n]*\n?",
    re.DOTALL,
)


def team_block_text(chain_rel_paths):
    """Render the team-context block, or '' when there is no chain (root mode).

    `chain_rel_paths` are level paths relative to the workspace root, forward-slashed
    (e.g. ["departments/marketing", "departments/marketing/teams/content"]).
    """
    if not chain_rel_paths:
        return ""
    lines = [TEAM_START, _TEAM_DOC]
    for rel in chain_rel_paths:
        rel_norm = str(rel).replace("\\", "/").rstrip("/")
        lines.append(f"@{rel_norm}/CLAUDE.md")
    lines.append(TEAM_END)
    return "\n".join(lines) + "\n"


def extract_team_block(text):
    """Return the literal team block (markers included) found in `text`, or ''."""
    m = _TEAM_BLOCK_RE.search(text or "")
    return m.group(0) if m else ""


def strip_team_block(text):
    """Return `text` with the team block removed and leading blank lines trimmed."""
    if not text:
        return ""
    return _TEAM_BLOCK_RE.sub("", text, count=1).lstrip("\n")


def join(team_block, personal_body):
    """Assemble CLAUDE.local.md from the team block and the personal remainder.

    No team block → the personal body verbatim (so a root-mode / team-less file
    is exactly the personal content, matching personal.sync's old contract).
    No personal body → just the team block.
    """
    team_block = team_block or ""
    personal_body = personal_body or ""
    if not team_block:
        return personal_body
    if not personal_body:
        return team_block
    return team_block.rstrip("\n") + "\n\n" + personal_body
